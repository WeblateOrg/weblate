def merge_roles(apps: StateApps, schema_editor: BaseDatabaseSchemaEditor) -> None:
    """Merge frozen defaults without changing local permission differences."""
    alias = schema_editor.connection.alias
    Role = apps.get_model("weblate_auth", "Role")
    Permission = apps.get_model("weblate_auth", "Permission")
    for codename, name in PERMISSION_LABELS.items():
        Permission.objects.using(alias).get_or_create(
            codename=codename, defaults={"name": name}
        )
    for name, defaults in NEW_DEFAULTS.items():
        role, created = Role.objects.using(alias).get_or_create(name=name)
        local = set(role.permissions.using(alias).values_list("codename", flat=True))
        new = set(defaults)
        if created or name not in OLD_DEFAULTS:
            merged = new
        else:
            old = set(OLD_DEFAULTS[name])
            merged = (new - (old - local)) | (local - old)
        if merged != local:
            role.permissions.set(
                Permission.objects.using(alias).filter(codename__in=merged)
            )


